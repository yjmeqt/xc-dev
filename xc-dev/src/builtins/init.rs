use std::path::Path;
use crate::error::{Result, XcDevError};

pub fn run(
    cwd: &Path,
    force: bool,
    _yes: bool,
    path: Option<&str>,
    scheme: Option<&str>,
) -> Result<i32> {
    let dotdir = cwd.join(".xc-dev");
    if dotdir.exists() && !force {
        return Err(XcDevError::Other(format!(
            ".xc-dev/ already exists at {} — pass --force to overwrite",
            dotdir.display()
        )));
    }
    std::fs::create_dir_all(&dotdir)
        .map_err(|source| XcDevError::Io { path: dotdir.clone(), source })?;

    // 1) path
    let path: String = match path {
        Some(p) => p.to_string(),
        None => match detect_project_path(cwd) {
            Some(p) => p,
            None => {
                eprintln!("xc-dev: warn: no unique .xcworkspace/.xcodeproj in {}; using REPLACE_ME", cwd.display());
                "REPLACE_ME.xcworkspace".to_string()
            }
        }
    };

    // 2) scheme
    let scheme: String = match scheme {
        Some(s) => s.to_string(),
        None => match detect_scheme(cwd, &path) {
            Some(s) => s,
            None => {
                eprintln!("xc-dev: warn: scheme not detected via xcodebuild; using REPLACE_ME");
                "REPLACE_ME".to_string()
            }
        }
    };

    // 3) build settings
    let (bundle_id, product_name, min_ios_version) =
        match detect_build_settings(cwd, &path, &scheme) {
            Some(t) => t,
            None => {
                eprintln!("xc-dev: warn: build settings not detected via xcodebuild; using placeholders");
                ("REPLACE_ME".into(), "REPLACE_ME".into(), "26.0".into())
            }
        };

    let project_toml = format!(r#"# .xc-dev/project.toml — generated by `xc-dev :proj init`
schema_version = 1

[project]
path             = "{path}"
scheme           = "{scheme}"
configuration    = "Debug"
bundle_id        = "{bundle_id}"
product_name     = "{product_name}"
min_ios_version  = "{min_ios_version}"

[vars]
# Add custom variables here:
# xcbeautify = "xcbeautify --quiet"
"#);
    write_file(&dotdir.join("project.toml"), &project_toml)?;

    let simulator_toml = r#"# .xc-dev/simulator.toml
schema_version = 1

# Populate with `xcrun simctl list devices`:
# [sim.default]
# id      = "ABC-123-..."
# name    = "iPhone 17 Pro"
# runtime = "iOS 26.2"
"#;
    write_file(&dotdir.join("simulator.toml"), simulator_toml)?;

    let tasks_toml = r#"# .xc-dev/tasks.toml
[tasks.build]
args = ["config=Debug"]
desc = "Build the app into .xc-dev/DerivedData"
cmd  = """
xcodebuild -scheme {{scheme}} \
  -configuration {{config}} \
  -derivedDataPath {{derived_data}} \
  build
"""

# Example tasks — uncomment to enable:
#
# [tasks.run]
# depends = ["build"]
# desc = "Boot the default simulator, install, launch"
# cmd  = """
# xcrun simctl boot {{sim_id}} 2>/dev/null || true
# xcrun simctl install {{sim_id}} {{app_path}}
# xcrun simctl launch {{sim_id}} {{bundle_id}}
# """
#
# [tasks.test-package]
# args = ["package"]
# desc = "Run unit tests for a SwiftPM package under Packages/"
# cmd  = "swift test --package-path Packages/{{package}}"
"#;
    write_file(&dotdir.join("tasks.toml"), tasks_toml)?;

    println!("Initialized .xc-dev/ at {}", dotdir.display());
    println!("Edit project.toml, populate simulator.toml, run `xc-dev :list`.");
    Ok(0)
}

fn write_file(path: &Path, contents: &str) -> Result<()> {
    std::fs::write(path, contents)
        .map_err(|source| XcDevError::Io { path: path.to_path_buf(), source })
}

fn detect_project_path(cwd: &Path) -> Option<String> {
    let mut workspaces = vec![];
    let mut projects = vec![];
    let entries = std::fs::read_dir(cwd).ok()?;
    for entry in entries.flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        if name.ends_with(".xcworkspace") { workspaces.push(name); }
        else if name.ends_with(".xcodeproj") { projects.push(name); }
    }
    if workspaces.len() == 1 { Some(workspaces.remove(0)) }
    else if workspaces.is_empty() && projects.len() == 1 { Some(projects.remove(0)) }
    else { None }
}

fn detect_scheme(cwd: &Path, path: &str) -> Option<String> {
    let flag = if path.ends_with(".xcworkspace") { "-workspace" } else { "-project" };
    let out = std::process::Command::new("xcodebuild")
        .args([flag, path, "-list", "-json"])
        .current_dir(cwd).output().ok()?;
    if !out.status.success() { return None; }
    let v: serde_json::Value = serde_json::from_slice(&out.stdout).ok()?;
    let schemes = v.pointer("/workspace/schemes")
        .or_else(|| v.pointer("/project/schemes"))?
        .as_array()?;
    if schemes.len() == 1 {
        schemes[0].as_str().map(String::from)
    } else {
        None
    }
}

fn detect_build_settings(cwd: &Path, path: &str, scheme: &str)
    -> Option<(String, String, String)>
{
    let flag = if path.ends_with(".xcworkspace") { "-workspace" } else { "-project" };
    let out = std::process::Command::new("xcodebuild")
        .args([flag, path, "-scheme", scheme, "-showBuildSettings", "-json"])
        .current_dir(cwd).output().ok()?;
    if !out.status.success() { return None; }
    let v: serde_json::Value = serde_json::from_slice(&out.stdout).ok()?;
    let bs = v.as_array()?.first()?.get("buildSettings")?;
    let bid = bs.get("PRODUCT_BUNDLE_IDENTIFIER")?.as_str()?.to_string();
    let pn  = bs.get("PRODUCT_NAME")?.as_str()?.to_string();
    let dt  = bs.get("IPHONEOS_DEPLOYMENT_TARGET")?.as_str()?.to_string();
    Some((bid, pn, dt))
}
